// One-off cleanup: applies the findings from classify-quiz-scope.mjs
// (others/quiz-scope-report.json + others/quiz-scope-recheck-report.json) to
// the actual quiz data — drops sets 6/7/8 wholesale (93-100% off-topic) and
// removes the 206 confirmed off-topic questions scattered across the other
// 21 sets, then regenerates src/quiz/meta.ts. No API calls, no cost.
// Run with: node scripts/apply-quiz-scope-cleanup.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dataDirs = ['src/quiz/data', 'src/quiz/data-es'];
const recheckReportFile = path.join(root, 'others/quiz-scope-recheck-report.json');
const metaFile = path.join(root, 'src/quiz/meta.ts');

const DROPPED_SETS = new Set([6, 7, 8]);

const recheck = JSON.parse(fs.readFileSync(recheckReportFile, 'utf8'));
const removeIds = new Set(recheck.confirmedOutOfScope.map((q) => q.id));

console.log(`Sets a eliminar completos: ${[...DROPPED_SETS].join(', ')}`);
console.log(`Preguntas puntuales a eliminar: ${removeIds.size}`);

for (const dir of dataDirs) {
  const fullDir = path.join(root, dir);
  const files = fs.readdirSync(fullDir).filter((f) => /^set-\d+\.json$/.test(f));
  for (const file of files) {
    const setNumber = Number(file.match(/\d+/)[0]);
    const filePath = path.join(fullDir, file);
    if (DROPPED_SETS.has(setNumber)) {
      fs.unlinkSync(filePath);
      continue;
    }
    const set = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    const before = set.questions.length;
    set.questions = set.questions.filter((q) => !removeIds.has(q.id));
    set.questionCount = set.questions.length;
    if (set.questions.length !== before) {
      fs.writeFileSync(filePath, JSON.stringify(set, null, 2) + '\n');
    }
  }
}

const enDir = path.join(root, 'src/quiz/data');
const files = fs
  .readdirSync(enDir)
  .filter((f) => /^set-\d+\.json$/.test(f))
  .sort((a, b) => Number(a.match(/\d+/)[0]) - Number(b.match(/\d+/)[0]));
const metaEntries = files.map((f) => {
  const set = JSON.parse(fs.readFileSync(path.join(enDir, f), 'utf8'));
  return { setNumber: set.setNumber, questionCount: set.questionCount };
});
const metaContent = `// AUTO-GENERATED by scripts/extract-quiz.mjs, curated by scripts/apply-quiz-scope-cleanup.mjs — do not hand-edit.
export interface QuizSetMeta {
  setNumber: number;
  questionCount: number;
}

export const quizSetsMeta: QuizSetMeta[] = ${JSON.stringify(metaEntries, null, 2)};
`;
fs.writeFileSync(metaFile, metaContent);

const totalQuestions = metaEntries.reduce((s, m) => s + m.questionCount, 0);
console.log(`Sets restantes: ${metaEntries.length}. Preguntas totales: ${totalQuestions}.`);

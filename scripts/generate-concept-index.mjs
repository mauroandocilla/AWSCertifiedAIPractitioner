// Regenerates src/quiz/conceptIndex.ts (the inverse concept -> question-refs
// index used by GlossaryEntryContent.tsx / RelatedQuestionsModal.tsx) from
// the `relatedConcepts` already written into both question banks by
// scripts/tag-quiz-concepts.mjs and scripts/tag-quiz-v2-concepts.mjs. No API
// calls, no cost -- run this after collecting both of those. Reads only the
// English set/questions files: relatedConcepts is language-independent and
// data-es/*.json's questions share the exact same `id`s (see
// scripts/classify-quiz-scope.mjs's tag-domains-collect, which relies on the
// same fact), so there's nothing to gain reading both.
import fs from 'node:fs';
import path from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dataDir = path.join(root, 'src/quiz/data');
const quizV2Path = path.join(root, 'src/quiz-v2/data/questions.json');
const outPath = path.join(root, 'src/quiz/conceptIndex.ts');

const index = {};
function addRef(conceptId, ref) {
  if (!index[conceptId]) index[conceptId] = [];
  index[conceptId].push(ref);
}

const setFiles = fs
  .readdirSync(dataDir)
  .filter((f) => /^set-\d+\.json$/.test(f))
  .sort((a, b) => Number(a.match(/\d+/)[0]) - Number(b.match(/\d+/)[0]));

for (const file of setFiles) {
  const set = JSON.parse(fs.readFileSync(path.join(dataDir, file), 'utf8'));
  for (const q of set.questions) {
    for (const conceptId of q.relatedConcepts ?? []) {
      addRef(conceptId, { bank: 'v1', setNumber: set.setNumber, id: q.id });
    }
  }
}

const v2Questions = JSON.parse(fs.readFileSync(quizV2Path, 'utf8'));
for (const q of v2Questions) {
  for (const conceptId of q.relatedConcepts ?? []) {
    addRef(conceptId, { bank: 'v2', id: q.id });
  }
}

const conceptCount = Object.keys(index).length;
const refCount = Object.values(index).reduce((n, refs) => n + refs.length, 0);

const content = `// AUTO-GENERATED by scripts/generate-concept-index.mjs — do not hand-edit.
// Inverse index: glossary term-card id (\`\${glossId}#\${cardIndex}\`, see
// src/conceptGraph.ts) -> the quiz questions (across both question banks)
// that test it. Kept as lightweight refs (not full question bodies) so
// GlossaryEntryContent.tsx can import this statically without pulling any
// quiz-set JSON into every domain/glossary page's bundle -- the actual
// question content is fetched lazily (see RelatedQuestionsModal.tsx) only
// once a concept's badge is clicked.
export type ConceptQuestionRef = { bank: 'v1'; setNumber: number; id: string } | { bank: 'v2'; id: string };

export const conceptIndex: Record<string, ConceptQuestionRef[]> = ${JSON.stringify(index, null, 2)};
`;

fs.writeFileSync(outPath, content);
console.log(`Escrito ${outPath}: ${conceptCount} conceptos con al menos una pregunta, ${refCount} referencias en total.`);
